/**
 * Writes DOCS/test-plan/unit-test-catalogue.md: every unit and component test, grouped by file,
 * read from `vitest list`. `--check` fails when the committed catalogue is out of date, so the
 * documented inventory and the suite cannot drift.
 *
 *   node scripts/gen-unit-catalogue.mjs           # regenerate
 *   node scripts/gen-unit-catalogue.mjs --check   # CI
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';

import { ROOT } from './lib/e2e-refs.mjs';

const OUT = join(ROOT, 'DOCS/test-plan/unit-test-catalogue.md');
const tmp = join(mkdtempSync(join(tmpdir(), 'mbo-vitest-list-')), 'list.json');
execFileSync('npx', ['vitest', 'list', `--json=${tmp}`], {
  cwd: ROOT,
  stdio: ['ignore', 'ignore', 'inherit'],
});
const tests = JSON.parse(readFileSync(tmp, 'utf8'));

const byFile = new Map();
for (const t of tests) {
  const file = relative(ROOT, t.file);
  if (!byFile.has(file)) byFile.set(file, { project: t.projectName, names: [] });
  byFile.get(file).names.push(t.name);
}

const lines = [
  '# Unit and component test catalogue',
  '',
  '<!-- Generated by `npm run docs:tests` from `vitest list`. Do not edit by hand. -->',
  '',
  `${tests.length} tests in ${byFile.size} files. Project \`node\` covers adapters, mappers, HTTP and`,
  'scripts; project `web` covers components through react-native-web in jsdom.',
  '',
];
for (const file of [...byFile.keys()].sort()) {
  const { project, names } = byFile.get(file);
  lines.push(`## \`${file}\` (${project})`, '');
  for (const name of names) lines.push(`- ${name.replaceAll('|', '\\|')}`);
  lines.push('');
}
const content = `${lines.join('\n').trimEnd()}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== content) {
    console.error(
      '✗ DOCS/test-plan/unit-test-catalogue.md is out of date. Run `npm run docs:tests`.',
    );
    process.exit(1);
  }
  console.log(`✓ unit-test catalogue is current (${tests.length} tests).`);
} else {
  writeFileSync(OUT, content);
  console.log(
    `[docs:tests] wrote ${relative(ROOT, OUT)} (${tests.length} tests, ${byFile.size} files).`,
  );
}
