import { z } from 'zod';

/**
 * True for an ISO `YYYY-MM-DD` string naming a real calendar day. `2026-02-30` is refused: the
 * server would refuse it too, but only after a round trip, and with a message about parsing.
 */
export function isRealIsoDate(value: string): boolean {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (!m) return false;
  const [y, mo, d] = [Number(m[1]), Number(m[2]), Number(m[3])];
  const date = new Date(Date.UTC(y, mo - 1, d));
  return date.getUTCFullYear() === y && date.getUTCMonth() === mo - 1 && date.getUTCDate() === d;
}

/** Today in the device's own calendar, as ISO. Read from the clock adapter by the caller. */
export function todayIso(nowMs: number): string {
  const d = new Date(nowMs);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

/** A required ISO date field. The message is an i18n key. */
export const isoDateField = z.string().trim().refine(isRealIsoDate, 'FORM.DATE_INVALID');
